(function fixedAudioOutputTests(){
"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const context=vm.createContext({window:{}});
for(const file of ["sample-data.js","transcript-contract.js","conversation-signals.js"])
 vm.runInContext(fs.readFileSync(file,"utf8"),context,{filename:file});
const {SEED,MAFerSignals:signals}=context.window;
const [unhappy,unclear,summaryFailed,sttFailed,happy,inProgress,neutral]=SEED.interactions;
const copy=record=>JSON.parse(JSON.stringify(record));
const close=record=>signals.customerClose(record);
assert.equal(signals.VERSION,"3.0");
assert.equal(close(unhappy).label,"Unhappy");
assert.equal(close(unhappy).evidence.speaker,"Customer");
assert.equal(close(unhappy).evidence.startMs,390000);
assert.equal(close(unclear).label,"Unclear","Missing closing evidence is not positive sentiment");
assert.equal(close(happy).label,"Happy");
assert.equal(close(happy).evidence.speaker,"Customer");
assert.equal(close(neutral).label,"Neutral");
assert.equal(close(summaryFailed).label,"Not available");
assert.equal(close(sttFailed).label,"Not available");
assert.equal(close(inProgress).label,"Not available");
const opening=copy(happy);opening.customerClose.segmentIndex=0;
assert.equal(close(opening).label,"Unclear","Opening words cannot establish closing sentiment");
const agentSpeech=copy(happy);agentSpeech.customerClose.segmentIndex=1;
assert.equal(close(agentSpeech).label,"Unclear","Agent words cannot establish customer happiness");
const laterCustomer=copy(happy);
laterCustomer.segments.push({startMs:426000,endMs:429000,speaker:"Customer",text:"Actually, I am still concerned."});
assert.equal(close(laterCustomer).label,"Unclear","Sentiment must reference the final customer turn");
assert.equal(signals.observations(unhappy,"emotionalIndicators")[0].type,"Frustration");
assert.equal(signals.observations(unhappy,"emotionalIndicators")[0].evidence.speaker,"Customer");
assert.equal(signals.observations(happy,"emotionalIndicators")[0].type,"Appreciation");
assert.equal(signals.observations(neutral,"emotionalIndicators")[0].type,"Reassurance");
assert.equal(signals.observations(unhappy,"interactionReferences")[0].type,"Commitment");
assert.equal(signals.observations(unclear,"interactionReferences")[0].type,"Key question");
assert.equal(signals.observations(unhappy,"conversationSignals").length,0,"No fabricated audio-only events");
assert.equal(signals.observations(summaryFailed,"emotionalIndicators").length,0);
const wrongSpeaker=copy(unhappy);wrongSpeaker.emotionalIndicators[0].speaker="Agent";
assert.equal(signals.observations(wrongSpeaker,"emotionalIndicators").length,0,"Speaker mismatch rejected");
const wrongType=copy(unhappy);wrongType.emotionalIndicators[0].type="QA score";
assert.equal(signals.observations(wrongType,"emotionalIndicators").length,0,"QA rubric fields are not observations");
const scored=copy(unhappy);scored.emotionalIndicators[0].score=99;scored.emotionalIndicators[0].passed=true;
const safe=signals.observations(scored,"emotionalIndicators")[0];
assert.equal("score" in safe,false,"No score in emitted observation");
assert.equal("passed" in safe,false,"No pass/fail flag in emitted observation");
const unverifiedAudio=copy(happy);
unverifiedAudio.conversationSignals=[{type:"Long silence",note:"Measured silence",source:"audio",startMs:50000,endMs:57000,speaker:"Unknown"}];
assert.equal(signals.observations(unverifiedAudio,"conversationSignals").length,0,"Audio event requires verified audio analysis");
unverifiedAudio.recordingRef="s3://synthetic-test-only/recording.wav";
unverifiedAudio.audioAnalysisVerified=true;
const verified=signals.observations(unverifiedAudio,"conversationSignals");
assert.equal(verified.length,1,"Verified audio interval can be referenced");
assert.equal(verified[0].evidence.source,"audio");
assert.equal(verified[0].evidence.recordingReference,"s3://synthetic-test-only/recording.wav");
const transcriptOnly=copy(happy);
transcriptOnly.conversationSignals=[{type:"Long silence",note:"Inferred from transcript",source:"transcript",segmentIndex:0,speaker:"Customer"}];
assert.equal(signals.observations(transcriptOnly,"conversationSignals").length,0,"Never infer silence from transcript");
const invalidTranscript=copy(happy);invalidTranscript.segments[2].endMs=null;
assert.equal(close(invalidTranscript).label,"Not available");
assert.equal(signals.observations(invalidTranscript,"emotionalIndicators").length,0);
const output=signals.buildOutput(unhappy);
assert.equal(output.outputSchemaVersion,"3.0");
assert.equal(output.transcription.segments[0].startMs,5000);
assert.equal(output.crmSummary.resolutionStatus,"Refund completion not verified");
assert.equal(output.customerSentiment.label,"Unhappy");
assert.equal(output.emotionalIndicators.length,1);
assert.equal(output.interactionReferences.length,1);
assert.equal(output.interactionMetadata.genesysConversationId,unhappy.id);
assert.equal(output.interactionMetadata.recordingReference,null,"No invented original audio URL");
assert.equal(output.processing.transcriptReady,true);
assert.equal(output.processing.summaryReady,true);
assert.equal("qaScore" in output,false);
assert.equal("eqHighlights" in output,false);
assert.equal(signals.buildOutput(summaryFailed).crmSummary.summary,null,"Failed summary must not masquerade as complete");
assert.equal(signals.buildOutput(invalidTranscript).processing.transcription,"failed");
assert.equal(signals.buildOutput(invalidTranscript).transcription.segments.length,0,"Invalid transcript must not be published");
console.log("Fixed audio output tests passed: closing sentiment, descriptive evidence, audio-only safeguards, no QA grading, structured output.");
})();
