(function conversationSignalTests(){
"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const context=vm.createContext({window:{}});
for(const file of ["sample-data.js","transcript-contract.js","conversation-signals.js"])
 vm.runInContext(fs.readFileSync(file,"utf8"),context,{filename:file});
const {SEED,MAFerSignals:signals}=context.window;
const [unhappy,unclear,summaryFailed,sttFailed,happy,inProgress,neutral]=SEED.interactions;
const close=record=>signals.customerClose(record);
assert.equal(close(unhappy).label,"Unhappy");
assert.equal(close(unhappy).evidence.speaker,"Customer");
assert.equal(close(unhappy).evidence.startMs,390000);
assert.equal(close(unclear).label,"Unclear","Insufficient closing evidence must not be assumed happy");
assert.equal(close(unclear).evidence,null);
assert.equal(close(happy).label,"Happy");
assert.equal(close(happy).evidence.speaker,"Customer");
assert.equal(close(neutral).label,"Neutral");
assert.equal(close(summaryFailed).label,"Not available");
assert.equal(close(sttFailed).label,"Not available");
assert.equal(close(inProgress).label,"Not available");
assert.equal(signals.eqHighlights(unhappy).length,1);
assert.equal(signals.eqHighlights(unhappy)[0].cue,"Emotional acknowledgement");
assert.equal(signals.eqHighlights(unhappy)[0].evidence.speaker,"Agent");
assert.equal(signals.eqHighlights(neutral)[0].cue,"Empathy");
assert.equal(signals.eqHighlights(summaryFailed).length,0);
assert.equal(signals.eqHighlights(unclear).length,0);
const copy=record=>JSON.parse(JSON.stringify(record));
const opening=copy(happy);opening.customerClose.segmentIndex=0;
assert.equal(close(opening).label,"Unclear","Opening statement cannot prove customer happiness at close");
const agentSpeech=copy(happy);agentSpeech.customerClose.segmentIndex=1;
assert.equal(close(agentSpeech).label,"Unclear","Agent words cannot prove customer happiness");
const laterCustomer=copy(happy);
laterCustomer.segments.push({startMs:426000,endMs:429000,speaker:"Customer",text:"Actually, I am still concerned."});
assert.equal(close(laterCustomer).label,"Unclear","Earlier positive statement cannot override a later customer closing turn");
const invalidTranscript=copy(happy);invalidTranscript.segments[2].endMs=null;
assert.equal(close(invalidTranscript).label,"Not available","Invalid STT timestamps must block sentiment");
assert.equal(signals.eqHighlights(invalidTranscript).length,0);
const wrongSpeaker=copy(unhappy);wrongSpeaker.eqHighlights[0].segmentIndex=0;
assert.equal(signals.eqHighlights(wrongSpeaker).length,0,"Customer words cannot be agent EQ evidence");
const wrongCue=copy(unhappy);wrongCue.eqHighlights[0].cue="QA compliance";
assert.equal(signals.eqHighlights(wrongCue).length,0,"EQ cues are not QA criteria");
const scored=copy(unhappy);scored.eqHighlights[0].score=99;scored.eqHighlights[0].passed=true;
const safe=signals.eqHighlights(scored)[0];
assert.equal("score" in safe,false,"EQ output must never expose scores");
assert.equal("passed" in safe,false,"EQ output must never expose pass/fail flags");
console.log("Conversation signals tests passed: closing-only customer sentiment, evidence-backed non-scored EQ and no QA grading.");
})();
